-- Nội dung:
--   1. Tạo bảng "CloudMediaFiles" lưu vết tệp Google Drive & fallback cục bộ (ISoftDelete)
--   2. Tạo 5 index tối ưu truy vấn trên "CloudMediaFiles"
--   3. Bổ sung khóa ngoại nullable (ON DELETE SET NULL) + index trên 6 bảng liên kết:
--      "ClassLessonDocuments", "ClassCurriculumDocuments", "ClassCurriculumVersions",
--      "RoomIncidentReports", "Students", "Users"
-- Lưu ý: Script viết theo chuẩn idempotent, chạy trực tiếp được trên pgAdmin Query Tool.
