-- -----------------------------------------------------------------------------------------
-- 1. TẠO BẢNG "CloudMediaFiles"
-- -----------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "CloudMediaFiles" (
    "Id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "Category" VARCHAR(50) NOT NULL,
    "EntityName" VARCHAR(80) NULL,
    "EntityId" BIGINT NULL,
    "OriginalFileName" VARCHAR(255) NOT NULL,
    "StoredFileName" VARCHAR(255) NOT NULL,
    "ContentType" VARCHAR(120) NOT NULL,
    "FileSize" BIGINT NOT NULL DEFAULT 0,
    "Sha256Hash" VARCHAR(64) NULL,
    "StorageProvider" VARCHAR(30) NOT NULL DEFAULT 'GOOGLE_DRIVE',
    "ExternalFileId" VARCHAR(150) NULL,
    "ExternalFolderId" VARCHAR(150) NULL,
    "DriveFolderPath" VARCHAR(300) NULL,
    "LocalFallbackPath" VARCHAR(500) NULL,
    "SyncStatus" VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    "RetryCount" INTEGER NOT NULL DEFAULT 0,
    "LastError" VARCHAR(1000) NULL,
    "UploadedBy" VARCHAR(100) NULL,
    "UploadedByUserId" BIGINT NULL,
    "CreatedAt" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    "UpdatedAt" TIMESTAMP WITHOUT TIME ZONE NULL,
    "SyncedAt" TIMESTAMP WITHOUT TIME ZONE NULL,
    "IsDeleted" BOOLEAN NOT NULL DEFAULT FALSE,
    "DeletedAt" TIMESTAMP WITHOUT TIME ZONE NULL,
    CONSTRAINT "PK_CloudMediaFiles" PRIMARY KEY ("Id")
);

CREATE INDEX IF NOT EXISTS "IX_CloudMediaFiles_Category_SyncStatus_CreatedAt"
    ON "CloudMediaFiles" ("Category", "SyncStatus", "CreatedAt");

CREATE INDEX IF NOT EXISTS "IX_CloudMediaFiles_EntityName_EntityId"
    ON "CloudMediaFiles" ("EntityName", "EntityId");

CREATE INDEX IF NOT EXISTS "IX_CloudMediaFiles_ExternalFileId"
    ON "CloudMediaFiles" ("ExternalFileId");

CREATE INDEX IF NOT EXISTS "IX_CloudMediaFiles_StorageProvider_SyncStatus"
    ON "CloudMediaFiles" ("StorageProvider", "SyncStatus");

CREATE INDEX IF NOT EXISTS "IX_CloudMediaFiles_IsDeleted"
    ON "CloudMediaFiles" ("IsDeleted");

-- -----------------------------------------------------------------------------------------
-- 2. BẢNG "ClassLessonDocuments" -> "CloudFileId"
-- -----------------------------------------------------------------------------------------
ALTER TABLE "ClassLessonDocuments"
    ADD COLUMN IF NOT EXISTS "CloudFileId" BIGINT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'FK_ClassLessonDocuments_CloudMediaFiles_CloudFileId'
    ) THEN
        ALTER TABLE "ClassLessonDocuments"
            ADD CONSTRAINT "FK_ClassLessonDocuments_CloudMediaFiles_CloudFileId"
            FOREIGN KEY ("CloudFileId")
            REFERENCES "CloudMediaFiles"("Id")
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "IX_ClassLessonDocuments_CloudFileId"
    ON "ClassLessonDocuments" ("CloudFileId");

